// Helper functions for filtering and searching
export const searchPlants = (query: string): IndividualPlant[] => {
  const lowerQuery = query.toLowerCase().trim();
  if (!lowerQuery) return INDIVIDUAL_PLANTS;

  return INDIVIDUAL_PLANTS.filter(
    (plant) =>
      plant.name.toLowerCase().includes(lowerQuery) ||
      plant.scientificName.toLowerCase().includes(lowerQuery) ||
      plant.description.toLowerCase().includes(lowerQuery) ||
      plant.category.toLowerCase().includes(lowerQuery)
  );
};

export const filterPlantsByPlacement = (placement: PlacementType): IndividualPlant[] => {
  return INDIVIDUAL_PLANTS.filter((plant) => plant.suitablePlacements.includes(placement));
};

export const filterPlantsBySize = (size: PlantSize): IndividualPlant[] => {
  return INDIVIDUAL_PLANTS.filter((plant) => plant.availableSizes.includes(size));
};

export const filterPlantsByCategory = (category: string): IndividualPlant[] => {
  return INDIVIDUAL_PLANTS.filter((plant) => plant.category === category);
};

export const getPlantById = (id: string): IndividualPlant | undefined => {
  return INDIVIDUAL_PLANTS.find((plant) => plant.id === id);
};
